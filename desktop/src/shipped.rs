const NOTES_PACKAGE: &str = "vessels/notes/";

pub fn files(notes: Absent) -> Vec<Shipped<'static>> {
    FILES
        .iter()
        .map(|(path, bytes)| Shipped {
            path,
            bytes,
            absent: if path.starts_with(NOTES_PACKAGE) {
                notes
            } else {
                Absent::Write
            },
        })
        .collect()
}
